export function getAvailableCountries(): CountryInfo[] {
  return COUNTRIES_AND_STATES;
}

export function getStatesForCountry(countryNameOrId: string): StateInfo[] {
  const match = COUNTRIES_AND_STATES.find(
    (c) => c.id.toLowerCase() === countryNameOrId.toLowerCase() || c.name.toLowerCase() === countryNameOrId.toLowerCase()
  );
  return match ? match.states : COUNTRIES_AND_STATES[0].states;
}

export function getFoodsForLocation(countryName?: string, stateName?: string): LocalizedDish[] {
  if (!countryName && !stateName) return LOCALIZED_FOOD_DATABASE;

  return LOCALIZED_FOOD_DATABASE.filter((dish) => {
    let matchesCountry = true;
    let matchesState = true;

    if (countryName && countryName !== 'all') {
      matchesCountry = dish.country.toLowerCase() === countryName.toLowerCase();
    }
    if (stateName && stateName !== 'all') {
      matchesState = dish.state.toLowerCase() === stateName.toLowerCase();
    }

    return matchesCountry && matchesState;
  });
}

export function searchLocationFoods(query: string, countryName?: string, stateName?: string): LocalizedDish[] {
  const base = getFoodsForLocation(countryName, stateName);
  if (!query.trim()) return base;

  const q = query.toLowerCase().trim();
  return base.filter((dish) => {
    return (
      dish.name.toLowerCase().includes(q) ||
      dish.category.toLowerCase().includes(q) ||
      dish.state.toLowerCase().includes(q) ||
      dish.country.toLowerCase().includes(q) ||
      dish.regionalNames.some((r) => r.toLowerCase().includes(q))
    );
  });
}

export function convertLocalizedToFoodItem(dish: LocalizedDish, portion: PortionSize = 'medium'): FoodItem {
  const factor = portion === 'small' ? 0.7 : portion === 'large' ? 1.4 : 1.0;

  return {
    id: dish.id,
    name: dish.name,
    category: dish.category,
    portion,
    portionMultiplier: factor,
    servingDescription: dish.servingDescription,
    calories: Math.round(dish.calories * factor),
    protein: Number((dish.protein * factor).toFixed(1)),
    carbs: Number((dish.carbs * factor).toFixed(1)),
    fat: Number((dish.fat * factor).toFixed(1)),
    saturatedFat: Number((dish.saturatedFat * factor).toFixed(1)),
    fiber: Number((dish.fiber * factor).toFixed(1)),
    sugar: Number((dish.sugar * factor).toFixed(1)),
    sodium: Math.round(dish.sodium * factor),
    cholesterol: Math.round(dish.cholesterol * factor),
    potassium: Math.round(dish.potassium * factor),
    calcium: Math.round(dish.calcium * factor),
    iron: Number((dish.iron * factor).toFixed(1)),
    glycemicIndexBand: dish.glycemicIndexBand,
    isHighProtein: dish.isHighProtein,
    cuisineRegion: dish.cuisineRegion,
    country: dish.country,
    state: dish.state,
    regionalNames: dish.regionalNames,
    thumbnail: dish.thumbnail,
    healthNote: dish.healthNote,
    confidenceTier: 'high',
    isConfirmed: true,
    originalPrediction: dish.name,
  };
}
