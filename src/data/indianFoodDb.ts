// Helper to find Indian food by query or alias
export function searchIndianFood(query: string): IndianFoodEntry[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return INDIAN_FOOD_DATABASE.slice(0, 15);

  return INDIAN_FOOD_DATABASE.filter((entry) => {
    if (entry.name.toLowerCase().includes(clean)) return true;
    if (entry.category.toLowerCase().includes(clean)) return true;
    if (entry.cuisineRegion.toLowerCase().includes(clean)) return true;
    return entry.regionalNames.some((alias) => alias.toLowerCase().includes(clean));
  });
}

// Helper to look up specific entry by exact or close name
export function findIndianFoodByName(name: string): IndianFoodEntry | undefined {
  const clean = name.trim().toLowerCase();
  return INDIAN_FOOD_DATABASE.find(
    (e) =>
      e.name.toLowerCase() === clean ||
      e.regionalNames.some((alias) => alias.toLowerCase() === clean) ||
      clean.includes(e.name.toLowerCase())
  );
}

